function ok = runWiLabHeldoutCase(configPath,runRoot,scenarioId,seed,density,speed,speedStd,policy)
%RUNWILABHELDOUTCASE Run one resumable held-out case in an isolated MATLAB process.
policy=string(policy); root=fileparts(mfilename('fullpath')); wilabRoot=fileparts(root); addpath(genpath(wilabRoot));
cfg=loadConfig(configPath); scenarioRoot=fullfile(runRoot,sprintf('scenario_%04d',scenarioId));
caseRoot=fullfile(scenarioRoot,policy); marker=fullfile(caseRoot,'COMPLETE.mat'); ok=false;
if isfile(marker), ok=true; return; end
if ~isfolder(caseRoot), mkdir(caseRoot); end
try
    cfgFile=fullfile(wilabRoot,'ConfigFiles','mode2_pipeline.cfg');
    if isfield(cfg.radio,'native_wilab_raw_m'), raw=cfg.radio.native_wilab_raw_m;
    else, raw=min(100,cfg.safety.receiver_range_m); end
    common={cfgFile,'Technology','NR-V2X','seed',seed,'simulationTime',cfg.experiment.duration_s, ...
        'rho',density,'roadLength',cfg.mobility.road_length_m,'vMean',speed,'vStDev',speedStd, ...
        'BwMHz',cfg.radio.bandwidth_mhz,'SCS_NR',cfg.radio.subcarrier_spacing_khz, ...
        'MCS_NR',cfg.radio.mcs_index,'sizeSubchannel',cfg.radio.resource_blocks_per_subchannel, ...
        'beaconSizeBytes',cfg.radio.max_transport_block_bytes, ...
        'generationInterval',cfg.safety.generation_interval_ms/1000, ...
        'allocationPeriod',cfg.radio.reservation_interval_ms/1000, ...
        'probResKeep',cfg.radio.sps_keep_probability,'cv2xNumberOfReplicasMax',1,'Raw',raw, ...
        'dcc_active',false,'cbrActive',true,'printCBR',false,'safetyOffloadingEnabled',true, ...
        'safetyOffloadingConfig',configPath};
    if policy=="no_offload", world="baseline"; else, world="policy"; end
    WiLabV2Xsim_final_policy_90(common{:},'outputFolder',caseRoot, ...
        'safetyOffloadingPolicy',policy,'safetyOffloadingWorld',world);
    if policy~="no_offload"
        baseRoot=fullfile(scenarioRoot,'no_offload');
        assert(isfile(fullfile(baseRoot,'COMPLETE.mat')),'Heldout:MissingBaseline','Baseline incomplete');
        B=readtable(fullfile(baseRoot,'safety_offloading','safety_packets.csv'),'VariableNamingRule','preserve');
        P=readtable(fullfile(caseRoot,'safety_offloading','safety_packets.csv'),'VariableNamingRule','preserve');
        T=readtable(fullfile(caseRoot,'safety_offloading','tasks.csv'),'VariableNamingRule','preserve');
        paired=pairOutcomes(B,P); writetable(paired,fullfile(caseRoot,'paired_outcomes.csv'));
        result=table(height(paired),mean(paired.harmful_flip),mean(~paired.policy_success), ...
            mean(~paired.baseline_success),mean(paired.avoided_failure),sum(T.completed_on_time), ...
            sum(T.fragment_count),'VariableNames',{'safety_opportunities','harm_probability', ...
            'policy_failure_probability','baseline_failure_probability','avoided_failure_probability', ...
            'tasks_completed','fragment_count'});
        writetable(result,fullfile(caseRoot,'case_result.csv'));
    end
    completedAt=datetime('now'); save(marker,'completedAt','scenarioId','seed','density','policy'); ok=true;
catch ME
    fid=fopen(fullfile(caseRoot,'FAILURE.txt'),'wt');
    if fid>=0, fprintf(fid,'%s\n\n%s',ME.message,getReport(ME,'extended')); fclose(fid); end
    rethrow(ME);
end
end
