function summary=runWiLabOpportunityGate(configPath,durationS,seed,density)
%RUNWILABOPPORTUNITYGATE Measure ideal, radio, and safety-feasible headroom.
arguments
    configPath (1,1) string = "config/training_data.json"
    durationS (1,1) double = 2
    seed (1,1) double = 4
    density (1,1) double = 50
end
root=fileparts(mfilename('fullpath')); repoRoot=fileparts(root); addpath(genpath(repoRoot));
if ~isfile(configPath), configPath=fullfile(root,configPath); end
cfg=loadConfig(configPath);
cfg.mobility.density_vehicles_per_km=density;
cfg.compute.arrival_model="poisson";
cfg.compute.arrival_rate_tasks_per_s=12;
cfg.compute.cycles_per_task=36000000;
cfg.compute.deadline_ms=100;
cfg.experiment.duration_s=durationS;
stamp=string(datetime('now','Format','yyyyMMdd_HHmmss_SSS'));
runRoot=fullfile(root,cfg.experiment.output_root,"opportunity_gate_"+stamp); mkdir(runRoot);
cases={"local_only","no_offload",false; ...
    "instant_oracle","oracle_instant",true; ...
    "radio_oracle","oracle_actual",false; ...
    "safety_oracle","safety_oracle",false; ...
    "risk_aware","risk_heuristic",false};
cfgFile=fullfile(repoRoot,'ConfigFiles','mode2_pipeline.cfg');
rows=cell(size(cases,1),11); baseSafety=table(); baseCompleted=0;
for ci=1:size(cases,1)
    label=string(cases{ci,1}); policy=string(cases{ci,2});
    cfg.compute.ideal_communication=cases{ci,3};
    caseRoot=fullfile(runRoot,label); mkdir(caseRoot);
    effectiveConfig=fullfile(caseRoot,'config.json');
    fid=fopen(effectiveConfig,'wt'); assert(fid>=0,'Gate:Config','Cannot write config');
    fprintf(fid,'%s',jsonencode(cfg,'PrettyPrint',true)); fclose(fid);
    common={cfgFile,'Technology','NR-V2X','seed',seed,'simulationTime',durationS, ...
        'rho',density,'roadLength',cfg.mobility.road_length_m, ...
        'vMean',cfg.mobility.speed_kmh_mean(1),'vStDev',cfg.mobility.speed_kmh_std(1), ...
        'BwMHz',cfg.radio.bandwidth_mhz,'SCS_NR',cfg.radio.subcarrier_spacing_khz, ...
        'MCS_NR',cfg.radio.mcs_index,'sizeSubchannel',cfg.radio.resource_blocks_per_subchannel, ...
        'beaconSizeBytes',cfg.radio.max_transport_block_bytes, ...
        'generationInterval',cfg.safety.generation_interval_ms/1000, ...
        'allocationPeriod',cfg.radio.reservation_interval_ms/1000, ...
        'T1autonomousMode',cfg.radio.slot_duration_ms,'T2autonomousMode',cfg.radio.selection_window_ms, ...
        'TsensingPeriod',cfg.radio.sensing_window_ms/1000, ...
        'ratioSelectedAutonomousMode',cfg.radio.candidate_fraction, ...
        'powerThresholdAutonomous',cfg.radio.sensing_threshold_dbm, ...
        'probResKeep',cfg.radio.sps_keep_probability,'cv2xNumberOfReplicasMax',1, ...
        'Raw',cfg.radio.native_wilab_raw_m,'dcc_active',false,'cbrActive',true,'printCBR',false, ...
        'safetyOffloadingEnabled',true,'safetyOffloadingConfig',effectiveConfig, ...
        'safetyOffloadingPolicy',policy,'safetyOffloadingWorld',label,'outputFolder',caseRoot};
    WiLabV2Xsim_final_policy_90(common{:});
    tasks=readtable(fullfile(caseRoot,'safety_offloading','tasks.csv'),'VariableNamingRule','preserve');
    safety=readtable(fullfile(caseRoot,'safety_offloading','safety_packets.csv'),'VariableNamingRule','preserve');
    if ci==1
        baseSafety=safety; baseCompleted=sum(tasks.completed_on_time);
        harm=0; avoided=0; prr=mean(safety.success_on_time);
    else
        paired=pairOutcomes(baseSafety,safety); writetable(paired,fullfile(caseRoot,'paired_outcomes.csv'));
        harm=mean(paired.harmful_flip); avoided=mean(paired.avoided_failure);
        prr=mean(paired.policy_success);
    end
    completed=sum(tasks.completed_on_time); offloaded=sum(string(tasks.action)=="offload");
    rows(ci,:)={label,policy,completed,height(tasks),completed-baseCompleted,offloaded, ...
        prr,harm,avoided,harm<=cfg.control.risk_harm_limit,caseRoot};
end
summary=cell2table(rows,'VariableNames',{'method','policy','completed','tasks','completion_gain', ...
    'offloaded','safety_prr','harm_probability','avoided_failure_probability', ...
    'safety_constraint_met','output_dir'});
writetable(summary,fullfile(runRoot,'opportunity_summary.csv'));
save(fullfile(runRoot,'opportunity_gate.mat'),'summary','cfg');
fprintf('Opportunity gate complete: %s\n',runRoot); disp(summary);
summary=summarizeWiLabOpportunityGate(runRoot);
end
