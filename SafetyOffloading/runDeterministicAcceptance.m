function [summary,details] = runDeterministicAcceptance()
%RUNDETERMINISTICACCEPTANCE Two simultaneous 36 Mcycle task gate.
root=fileparts(mfilename('fullpath')); repoRoot=fileparts(root); addpath(genpath(repoRoot));
cfg=loadConfig(fullfile(root,'config','training_data.json'));
cfg.mobility.road_length_m=1000;
cfg.mobility.density_vehicles_per_km=50;
cfg.mobility.speed_kmh_mean=110;
cfg.mobility.speed_kmh_std=11;
cfg.compute.cycles_per_task=36000000;
cfg.compute.deadline_ms=100;
cfg.compute.origin_ids=1;
% Release after one complete sensing window so this test measures the
% offloading path rather than Mode-2 cold-start initialization.
cfg.compute.deterministic_release_ms=[150,150];
cfg.compute.deterministic_origin_ids=[1,1];
cfg.compute.cpu_cycles_per_s_min=2000000000;
cfg.compute.cpu_cycles_per_s_max=2000000000;
cfg.compute.cpu_override_ids=1;
cfg.compute.cpu_override_cycles_per_s=500000000;
cfg.experiment.duration_s=0.5;

stamp=string(datetime('now','Format','yyyyMMdd_HHmmss_SSS'));
runRoot=fullfile(root,cfg.experiment.output_root,"acceptance_"+stamp);
mkdir(runRoot);
cases={"local_only","no_offload",false; ...
       "ideal_helper","acceptance_split",true; ...
       "mode2_helper","acceptance_split",false};
rows=cell(size(cases,1),7); details=table();
for ci=1:size(cases,1)
    label=cases{ci,1}; policy=cases{ci,2}; cfg.compute.ideal_communication=cases{ci,3};
    caseRoot=fullfile(runRoot,label); mkdir(caseRoot);
    configPath=fullfile(caseRoot,'config.json');
    fid=fopen(configPath,'wt'); assert(fid>=0,'Acceptance:Config','Cannot write config');
    fprintf(fid,'%s',jsonencode(cfg,'PrettyPrint',true)); fclose(fid);
    cfgFile=fullfile(repoRoot,'ConfigFiles','mode2_pipeline.cfg');
    common={cfgFile,'Technology','NR-V2X','seed',91001,'simulationTime',cfg.experiment.duration_s, ...
        'rho',cfg.mobility.density_vehicles_per_km,'roadLength',cfg.mobility.road_length_m, ...
        'vMean',cfg.mobility.speed_kmh_mean,'vStDev',cfg.mobility.speed_kmh_std, ...
        'BwMHz',cfg.radio.bandwidth_mhz,'SCS_NR',cfg.radio.subcarrier_spacing_khz, ...
        'MCS_NR',cfg.radio.mcs_index,'sizeSubchannel',cfg.radio.resource_blocks_per_subchannel, ...
        'beaconSizeBytes',cfg.radio.max_transport_block_bytes, ...
        'generationInterval',cfg.safety.generation_interval_ms/1000, ...
        'allocationPeriod',cfg.radio.reservation_interval_ms/1000, ...
        'T1autonomousMode',cfg.radio.slot_duration_ms,'T2autonomousMode',cfg.radio.selection_window_ms, ...
        'TsensingPeriod',cfg.radio.sensing_window_ms/1000, ...
        'ratioSelectedAutonomousMode',cfg.radio.candidate_fraction, ...
        'powerThresholdAutonomous',cfg.radio.sensing_threshold_dbm, ...
        'probResKeep',cfg.radio.sps_keep_probability,'cv2xNumberOfReplicasMax',1, ...
        'Raw',cfg.radio.native_wilab_raw_m,'dcc_active',false,'cbrActive',true,'printCBR',false, ...
        'safetyOffloadingEnabled',true,'safetyOffloadingConfig',configPath, ...
        'safetyOffloadingPolicy',policy,'safetyOffloadingWorld',"policy",'outputFolder',caseRoot};
    WiLabV2Xsim_final_policy_90(common{:});
    tasks=readtable(fullfile(caseRoot,'safety_offloading','tasks.csv'),'VariableNamingRule','preserve');
    tasks.case_id=repmat(string(label),height(tasks),1);
    if isempty(details), details=tasks; else, details=[details;tasks]; end %#ok<AGROW>
    rows(ci,:)={label,sum(tasks.completed_on_time),height(tasks), ...
        strjoin(unique(string(tasks.action)),','), ...
        sum(string(tasks.action)=="offload"), ...
        sum(~isnan(tasks.input_delivered_ms)),caseRoot};
end
summary=cell2table(rows,'VariableNames',{'case_id','completed','tasks','actions', ...
    'offloaded','inputs_delivered','output_dir'});
assert(summary.completed(summary.case_id=="local_only")==1, ...
    'Acceptance:LocalCPU','Local-only must complete exactly one of two tasks');
assert(summary.completed(summary.case_id=="ideal_helper")==2, ...
    'Acceptance:IdealHelper','Ideal helper communication must complete both tasks');
actualCompleted=summary.completed(summary.case_id=="mode2_helper");
assert(actualCompleted>=1 && actualCompleted<=2, ...
    'Acceptance:Mode2','Mode-2 result must be one or two completed tasks');
writetable(summary,fullfile(runRoot,'acceptance_summary.csv'));
writetable(details,fullfile(runRoot,'acceptance_tasks.csv'));
save(fullfile(runRoot,'acceptance.mat'),'summary','details','cfg');
fprintf('Acceptance test complete: %s\n',runRoot); disp(summary);
end
