function summary = runWiLabIntegratedSmoke()
%RUNWILABINTEGRATEDSMOKE Exercise the overlay through WiLab's NR event loop.
root=fileparts(mfilename('fullpath')); wilabRoot=fileparts(root); addpath(genpath(wilabRoot));
stamp=string(datetime('now','Format','yyyyMMdd_HHmmss'));
runRoot=fullfile(root,"outputs","wilab_integrated_"+stamp);
baseOut=fullfile(runRoot,"baseline"); policyOut=fullfile(runRoot,"unrestricted");
cfgFile=fullfile(wilabRoot,"ConfigFiles","mode2_pipeline.cfg");
overlayCfg=fullfile(root,"config","smoke.json");
common={cfgFile,'Technology','NR-V2X','seed',31,'simulationTime',0.5,'rho',6, ...
    'roadLength',1000,'BwMHz',20,'SCS_NR',30,'MCS_NR',12,'sizeSubchannel',10, ...
    'beaconSizeBytes',1180,'generationInterval',0.1,'allocationPeriod',0.1, ...
    'probResKeep',0.8,'cv2xNumberOfReplicasMax',1,'Raw',100, ...
    'dcc_active',false,'cbrActive',true,'printCBR',false,'safetyOffloadingEnabled',true, ...
    'safetyOffloadingConfig',overlayCfg};

WiLabV2Xsim_final_policy_90(common{:},'outputFolder',baseOut, ...
    'safetyOffloadingPolicy','no_offload','safetyOffloadingWorld','baseline');
WiLabV2Xsim_final_policy_90(common{:},'outputFolder',policyOut, ...
    'safetyOffloadingPolicy','unrestricted','safetyOffloadingWorld','policy');

B=readtable(fullfile(baseOut,"safety_offloading","safety_packets.csv"), ...
    'VariableNamingRule','preserve');
P=readtable(fullfile(policyOut,"safety_offloading","safety_packets.csv"), ...
    'VariableNamingRule','preserve');
paired=pairOutcomes(B,P); writetable(paired,fullfile(runRoot,"paired_outcomes.csv"));
n=height(paired); summary=table(n,mean(paired.harmful_flip),mean(~paired.policy_success), ...
    mean(~paired.baseline_success),sum(paired.avoided_failure), ...
    'VariableNames',{'safety_opportunities','harm_probability','policy_failure_probability', ...
    'baseline_failure_probability','avoided_failure_count'});
writetable(summary,fullfile(runRoot,"summary.csv"));
fprintf("Integrated WiLab smoke complete: %s\n",runRoot); disp(summary);
end

